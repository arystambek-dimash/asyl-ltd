"""Номер телефона клиента: казахстанская запись 8XXXXXXXXXX и номер для чатов."""
import pytest

from apps.clients.phone import chat_phone, kz_local_phone


@pytest.mark.parametrize(("raw", "expected"), [
    ("+7 (702) 936-80-80", "87029368080"),
    ("87029368080", "87029368080"),
    ("77029368080", "87029368080"),
    ("702 936 80 80", "87029368080"),
    # Не +7: Узбекистан, недонабранный и пустой номер.
    ("+998 90 111 22 33", ""),
    ("702 936 80", ""),
    ("", ""),
])
def test_kz_local_phone(raw, expected):
    assert kz_local_phone(raw) == expected


@pytest.mark.parametrize(("raw", "expected"), [
    # +7 — как пишут в чатах: 8 и десять цифр.
    ("+7 (702) 936-80-80", "87029368080"),
    ("87029368080", "87029368080"),
    # Другие страны — с кодом страны после «+».
    ("+998 90 111 22 33", "+998901112233"),
    ("+996 555 123-456", "+996555123456"),
    # «+» и не 7 — номер чужой страны, даже если цифр как у казахстанского.
    ("+81 3 1234 5678", "+81312345678"),
    ("", ""),
    ("  ", ""),
])
def test_chat_phone(raw, expected):
    assert chat_phone(raw) == expected
